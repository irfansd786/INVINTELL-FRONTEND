  const whIdx = index % 3;
  const statuses = ["PENDING", "ALLOCATED", "PICKING", "PACKED", "DISPATCHED", "FULFILLED"];
  const status = statuses[index % statuses.length];

  return {
    id: `ord-csv-${index + 1}`,
    orderNumber: `ORD-2022-${9001 + index}`,
    customerName: `CSV Commercial Client ${index + 1}`,
    productName: p.productName,
    productId: p.productId,
    sku: p.sku,
    items: p.unitsOrdered,
    totalItems: p.unitsOrdered,
    totalValue: Math.round(p.unitsOrdered * p.sellingPrice * 0.8 * 100) / 100,
    status: status,
    priority: index % 3 === 0 ? "URGENT" : (index % 3 === 1 ? "HIGH" : "STANDARD"),
    warehouseName: whNames[whIdx],
    warehouseId: whIds[whIdx],
    createdAt: `2022-01-${String((index % 28) + 1).padStart(2, '0')}`
  };
